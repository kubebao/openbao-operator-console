#!/usr/bin/env bash
# Generates THIRD_PARTY_LICENSES for the console binary and image.
#
# Go: dependencies linked into ./cmd/console for linux, reported by go-licenses,
# plus the Go standard library. Web: production dependencies of web/, including
# the DM Sans and DM Mono fonts that the web assets embed.
#
# Requires Go, pnpm with web/node_modules installed (make install), and jq.
set -euo pipefail
cd "$(dirname "$0")/.."

GO_LICENSES=github.com/google/go-licenses/v2@v2.0.1
MODULE=github.com/kubebao/openbao-operator-console
output=${1:-THIRD_PARTY_LICENSES}

scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT

# One tab-separated line per package and license: name, version, license, path.
cat > "$scratch/go.tmpl" <<'EOF'
{{ range . }}{{ .Name }}	{{ .Version }}	{{ .LicenseName }}	{{ .LicensePath }}
{{ end }}
EOF
# Build the tool for the host, then report the dependencies of the Linux image build.
GOBIN="$scratch" go install "$GO_LICENSES"
GOOS=linux GOARCH=amd64 CGO_ENABLED=0 "$scratch/go-licenses" report ./cmd/console \
  --ignore "$MODULE" --template "$scratch/go.tmpl" 2> "$scratch/go.log" > "$scratch/go.tsv" || {
  cat "$scratch/go.log" >&2
  exit 1
}
if grep -q $'\tUnknown\t' "$scratch/go.tsv"; then
  echo "go-licenses could not identify a license:" >&2
  grep $'\tUnknown\t' "$scratch/go.tsv" >&2
  exit 1
fi

pnpm --dir web licenses list --prod --json > "$scratch/web.json"

separator() {
  printf '\n%s\n\n' '--------------------------------------------------------------------------------'
}

{
  cat <<'EOF'
Third-party software notices for the OpenBao Operator Console

The console binary and container image include the third-party software listed below. This file is generated by
scripts/third-party-licenses.sh (make licenses); do not edit it by hand.

The OpenBao Operator Console itself is licensed under the Apache License 2.0; see LICENSE.

================================================================================
Go modules linked into the console binary
================================================================================
EOF

  separator
  printf 'Go standard library and runtime\nLicense: BSD-3-Clause\n\n'
  cat "$(go env GOROOT)/LICENSE"

  # Group license names per package; packages sharing one license file keep one copy of the text.
  LC_ALL=C sort -t $'\t' -k1,1 -k3,3 "$scratch/go.tsv" | awk -F '\t' '
    NF == 4 {
      if ($1 != name) {
        if (name != "") print name "\t" version "\t" licenses "\t" path
        name = $1; version = $2; licenses = $3; path = $4
      } else {
        licenses = licenses ", " $3
      }
    }
    END { if (name != "") print name "\t" version "\t" licenses "\t" path }
  ' > "$scratch/go-grouped.tsv"
  while IFS=$'\t' read -r name version licenses path; do
    separator
    printf '%s %s\nLicense: %s\n\n' "$name" "$version" "$licenses"
    cat "$path"
  done < "$scratch/go-grouped.tsv"

  cat <<'EOF'

================================================================================
Web application production dependencies, including embedded fonts
================================================================================
EOF

  jq -r '[.[][] | {name, version: (.versions | join(", ")), license, path: .paths[0], homepage}]
    | sort_by(.name) | .[] | [.name, .version, .license, .path, (.homepage // "")] | @tsv' "$scratch/web.json" |
    while IFS=$'\t' read -r name version license path homepage; do
      separator
      printf '%s %s\nLicense: %s\n\n' "$name" "$version" "$license"
      text=$(find "$path" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' \) |
        LC_ALL=C sort | head -n 1)
      if [[ -n "$text" ]]; then
        cat "$text"
      else
        printf 'The package does not include a license file. See %s.\n' "${homepage:-https://www.npmjs.com/package/$name}"
      fi
    done
} > "$scratch/THIRD_PARTY_LICENSES"

# Normalize line endings and trailing whitespace so the output is stable across platforms.
tr -d '\r' < "$scratch/THIRD_PARTY_LICENSES" | sed -e 's/[[:space:]]*$//' | cat -s > "$output"
